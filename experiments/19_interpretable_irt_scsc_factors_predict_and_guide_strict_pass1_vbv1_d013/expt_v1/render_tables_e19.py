"""TLDR: Render experiment 19's analysis_e19.json into results_tables_e19.md (every statistic the results page cites, with intervals and p-values), and score the frozen forecast of the lane's own outcomes."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def f(x, nd=4):
    return "n/a" if x is None else f"{x:.{nd}f}"


def iv(c, nd=4):
    if c is None:
        return "n/a"
    lo, hi = c["ci95"] if c.get("ci95") else (None, None)
    p = c.get("p_two_sided")
    return f"{f(c['estimate'], nd)} [{f(lo, nd)}, {f(hi, nd)}] p-val={f(p, 4) if p is not None else 'n/a'}"


def lookup(r: dict, fid: str):
    """Outcome value of each frozen numeric prediction or event, by id."""
    g, e1 = r["G1"], r["E1"]
    v = r["verdicts"]
    table = {
        "G1_auc_primary": g["estimates"]["auc_mixed"]["q8_irt_2pl"],
        "G1_auc_panel_strict_rate": g["estimates"]["auc_mixed"]["panel_strict_rate"],
        "G1_auc_panel_mean_smooth": g["estimates"]["auc_mixed"]["panel_mean_smooth"],
        "G1_auc_features_only": g["estimates"]["auc_mixed"]["q8_features_only"],
        "G1_topk_mixed_share_primary": g["estimates"]["topk_mixed_share"]["q8_irt_2pl"],
        "E1_strict_m1_minus_m2": e1["strict"]["contrasts"]["m1_minus_m2"]["estimate"],
        "E1_strict_m2_minus_m3": e1["strict"]["contrasts"]["m2_minus_m3"]["estimate"],
        "E3_rho_median": r["E3"]["heldout"]["rho_median"],
        "E3b_spearman_strict_vs_fsc1": r["E3"]["item_level"]["strict__fsc_eq_1"]["spearman"],
        "G1_pass": g["auc_primary_vs_gate"]["estimate"] >= 0.70,
        "G1_irt_specific": v["G1"] == "PASS, IRT-SPECIFIC",
        "E1_strict_irt_beats_baselines": v["E1_strict_irt_beats_baselines"],
        "E1_harsh_irt_beats_baselines": v["E1_harsh_irt_beats_baselines"],
        "E1_strict_fsc_skill_adds": v["E1_strict_fsc_skill_adds"],
        "E1_harsh_fsc_skill_adds": v["E1_harsh_fsc_skill_adds"],
        "E1_strict_smooth_worse": v["E1_strict_smooth_vs_rate"] == "smooth worse",
        "E1_strict_smooth_better": v["E1_strict_smooth_vs_rate"] == "smooth better",
        "E2_strict_features_predict_unseen": v["E2_strict_features_predict_unseen_tasks"],
        "E2_harsh_features_predict_unseen": v["E2_harsh_features_predict_unseen_tasks"],
        "E3_two_skills": v["E3_two_skills"],
        "E1_gold_m1_minus_m2": e1["gold"]["contrasts"]["m1_minus_m2"]["estimate"],
        "E1c_gold_mae_smooth_calibrated": r["E1_system"]["gold"]["mae"]["smooth_calibrated"],
        "E1c_gold_mae_rate_calibrated": r["E1_system"]["gold"]["mae"]["rate_calibrated"],
        "E1_gold_irt_beats_baselines": v["E1_gold_irt_beats_baselines"],
        "E1_gold_smooth_worse": v["E1_gold_smooth_vs_rate"] == "smooth worse",
        "E1_gold_smooth_better": v["E1_gold_smooth_vs_rate"] == "smooth better",
        "E2_gold_features_predict_unseen": v["E2_gold_features_predict_unseen_tasks"],
    }
    return table[fid]


def score_forecast(r: dict, fc: dict) -> tuple[list[str], dict]:
    lines, inside, brier = [], 0, []
    for p in fc["numeric"]:
        val = lookup(r, p["id"])
        ok = val is not None and p["interval80"][0] <= val <= p["interval80"][1]
        inside += int(ok)
        lines.append(f"| {p['id']} | {p['point']} [{p['interval80'][0]}, {p['interval80'][1]}] | {f(val)} | {'inside' if ok else 'outside'} |")
    for p in fc["events"]:
        hit = bool(lookup(r, p["id"]))
        brier.append((p["p"] - float(hit)) ** 2)
        lines.append(f"| {p['id']} | P = {p['p']} | {hit} | Brier {(p['p'] - float(hit)) ** 2:.3f} |")
    return lines, {"numeric_inside_80": f"{inside}/{len(fc['numeric'])}",
                   "mean_brier": sum(brier) / len(brier), "events": len(brier)}


def render(r: dict, fc: dict) -> str:
    out = ["# Experiment 19 result tables (generated from expt_v1/results/analysis_e19.json)", "",
           "**Doc link:** <https://github.com/brando90/rl-4-code-verification/blob/main/experiments/19_interpretable_irt_scsc_factors_predict_and_guide_strict_pass1_vbv1_d013/expt_v1/results/results_tables_e19.md>",
           "", "**TLDR:** Every number the results page cites, generated by `render_tables_e19.py`; intervals are 95% bootstraps over "
           "validation task groups unless a row says otherwise, written x [lo, hi] p-val=Z (two-sided percentile bootstrap, null = zero difference).", ""]
    out += ["## Verdicts (mechanical, PROTOCOL.md section 4)", "", "| Rule | Verdict |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in r["verdicts"].items()]
    out += ["", f"Numerical gates: all primary fits converged = {r['gates']['all_primary_fits_converged']}; failures: {r['gates']['failures'] or 'none'}.", ""]
    reg = r["R0_regularization"]["chosen"]
    out += ["## R0 regularization (train cells only)", "", "| Model | slope SD | intercept residual SD | CV log loss |", "|---|---|---|---|"]
    out += [f"| {k} | {v['slope_sd']} | {v['sigma_e']} | {f(v['cv_logloss'])} |" for k, v in reg.items()]
    g = r["G1"]
    out += ["", f"## G1: forecasting the start policy's mixed strict groups ({g['n_tasks']} validation tasks, {g['n_groups']} groups)", "",
            f"Mixed tasks {g['mixed_tasks']}/{g['n_tasks']}; solvable (k >= 1) {g['solvable_tasks']}/{g['n_tasks']}; A6 rate {f(g['a6_rate'])}.", "",
            "| Score | AUC mixed [95% CI] | AUC solvable | top-quarter mixed share [95% CI] |", "|---|---|---|---|"]
    for n, a in g["estimates"]["auc_mixed"].items():
        key = n.replace("q8_", "")
        sol = g["estimates"]["auc_solvable"].get(key)
        tk = g["estimates"]["topk_mixed_share"][n]
        out.append(f"| {n} | {f(a)} [{f(g['auc_ci95'][n][0])}, {f(g['auc_ci95'][n][1])}] | {f(sol)} | {f(tk)} [{f(g['topk_ci95'][n][0])}, {f(g['topk_ci95'][n][1])}] |")
    pv = g["auc_primary_vs_gate"]
    out += ["", f"Primary vs gate 0.70 ({pv['gate_source']}): {f(pv['estimate'])} [{f(pv['ci95'][0])}, {f(pv['ci95'][1])}], one-sided p(AUC <= 0.70) = {f(pv['p_one_sided_le_gate'])} ({pv['p_test']}).", ""]
    out += ["| AUC contrast | estimate [95% CI] p-val |", "|---|---|"] + [f"| {k} | {iv(c)} |" for k, c in g["auc_contrasts"].items()]
    out += ["", f"Uniform mixed share {f(g['estimates']['uniform_mixed_share'])}; arm-C sequence share {f(g['estimates']['armc_mixed_share'])}, difference {iv(g['armc_minus_uniform'])}.",
            "", "| Top-quarter minus uniform | estimate [95% CI] p-val |", "|---|---|"]
    out += [f"| {k} | {iv(c)} |" for k, c in g["topk_minus_uniform"].items()]
    em = g["expected_mixed_groups_per_256_rollout_update_G8"]
    out += ["", f"Expected mixed groups per 256-rollout update at G = 8: uniform {f(em['uniform'], 2)}, top quarter {f(em['topk_irt'], 2)}, arm C {f(em['armc'], 2)}.", ""]
    cal = g["calibration"]
    out += ["| Forecast | mean predicted | bias (pred - obs) | binomial log loss | Pearson / Spearman / Kendall with k/8 |", "|---|---|---|---|---|"]
    for n, mp in cal["mean_predicted"].items():
        c3 = cal["correlation_p_vs_k_over_8"][n]
        out.append(f"| {n} | {f(mp)} | {f(cal['mean_bias_predicted_minus_observed'][n])} | {f(cal['binomial_logloss'][n])} | {f(c3['pearson'],3)} / {f(c3['spearman'],3)} / {f(c3['kendall'],3)} |")
    out += [f"| constant A6 rate | {f(g['a6_rate'])} | {f(g['a6_rate'] - cal['mean_observed'])} | {f(cal['binomial_logloss']['constant_a6_rate'])} | n/a |",
            "", f"Observed mean rate {f(cal['mean_observed'])} (k/8 pooled).", "", "| Sensitivity | AUC mixed | theta0 |", "|---|---|---|"]
    out += [f"| {k} | {f(v['auc_mixed'])} | {f(v['theta0'], 3)} |" for k, v in g["sensitivity"].items()]
    for t in ("strict", "harsh", "gold"):
        e = r["E1"][t]
        out += ["", f"## E1 ({t}): held-out system, validation cells ({e['cells']} cells, {e['positives']} positives)", "",
                "| Method | mean log loss | mean Brier |", "|---|---|---|"]
        out += [f"| {k} | {f(v)} | {f(e['mean_brier'][k])} |" for k, v in e["mean_logloss"].items()]
        out += ["", "| Contrast (log loss) | estimate [95% CI] p-val |", "|---|---|"] + [f"| {k} | {iv(c)} |" for k, c in e["contrasts"].items()]
        s = r["E1_system"][t]
        out += ["", f"E1c ({t}), system level, n = 11 ({s['interval_scope']}); mean observed {f(s['mean_observed'])}:", "",
                "| Forecast | MAE | mean forecast | bias (forecast - observed) | Pearson / Spearman / Kendall |", "|---|---|---|---|---|"]
        for k, v in s["mae"].items():
            c3 = s["correlation_with_observed"][k]
            out.append(f"| {k} | {f(v)} | {f(s['mean_forecast'][k])} | {f(s['mean_bias_forecast_minus_observed'][k])} | {f(c3['pearson'],3)} / {f(c3['spearman'],3)} / {f(c3['kendall'],3)} |")
        out += ["", "| MAE contrast | estimate [95% CI] p-val |", "|---|---|"] + [f"| {k} | {iv(c)} |" for k, c in s["mae_contrasts"].items()]
        out += ["", "| System | observed validation rate | " + " | ".join(s["forecasts"]) + " |", "|---|---|" + "---|" * len(s["forecasts"])]
        for i, name in enumerate(s["systems"]):
            out.append(f"| {name} | {f(s['observed_validation_rate'][i], 3)} | " + " | ".join(f(s["forecasts"][k][i], 3) for k in s["forecasts"]) + " |")
    out += ["", "## E2: task features", ""]
    for t in ("strict", "harsh", "gold"):
        c = r["E2"]["coefficients"][t]
        nt = r["E2"]["new_task"][t]
        out += [f"### {t}: explanatory 2PL on train items (slope SD {c['regularization']['slope_sd']}, residual SD {c['regularization']['sigma_e']}); "
                f"features explain {f(c['intercept_variance_explained'], 3)} of intercept variance; {c['boot_converged']}/{c['boot_draws']} refits converged", "",
                "| Feature | coefficient (logit per SD, + = easier) [95% refit CI] p-val |", "|---|---|"]
        out += [f"| {row['feature']} | {f(row['coef'], 3)} [{f(row['ci95'][0], 3) if row['ci95'] else 'n/a'}, {f(row['ci95'][1], 3) if row['ci95'] else 'n/a'}] p-val={f(row['p_two_sided'], 4) if row['p_two_sided'] is not None else 'n/a'} |"
                for row in c["coefficients"]]
        out += ["", f"New-task test on validation ({nt['cells']} cells): log loss with features {f(nt['mean_logloss_features'])}, without {f(nt['mean_logloss_no_features'])}; "
                f"no-features minus features {iv(nt['nofeat_minus_feat'])}.", ""]
    h = r["E3"]["heldout"]
    out += ["## E3: one skill or two", "", f"Held-out log density per cell: two skills {f(h['mean_log_density']['m3'])}, tied {f(h['mean_log_density']['m3t'])}; "
            f"untied minus tied {iv(h['untied_minus_tied'])}. Fitted rho by fold: median {f(h['rho_median'], 3)}, range [{f(h['rho_range'][0], 3)}, {f(h['rho_range'][1], 3)}].", ""]
    il = r["E3"]["item_level"]
    out += [f"Item-level intercept correlations (items with >= 3 RC cells: {il['items_with_3plus_rc_cells']}; 1,000 item-group bootstraps):", "",
            "| Pair | n | Pearson [CI] | Spearman [CI] | Kendall [CI] |", "|---|---|---|---|---|"]
    for k in ("strict__fsc_eq_1", "strict__rc_fspecs_eq_1", "fsc_eq_1__rc_fspecs_eq_1"):
        v = il[k]
        cell = lambda m: f"{f(v[m], 3)} [{f(v[m + '_ci95'][0], 3)}, {f(v[m + '_ci95'][1], 3)}]" if v[m] is not None and v[m + "_ci95"] else "n/a"  # noqa: E731
        out.append(f"| {k} | {v['n']} | {cell('pearson')} | {cell('spearman')} | {cell('kendall')} |")
    for title, fcx in fc.items():
        lines, summ = score_forecast(r, fcx)
        out += ["", f"## Frozen forecast `{title}` of this lane's own outcomes, scored", "",
                f"Numeric predictions inside their 80% intervals: {summ['numeric_inside_80']}; mean Brier on {summ['events']} events: {summ['mean_brier']:.3f}.", "",
                "| Prediction | Forecast | Outcome | Score |", "|---|---|---|---|"] + lines
    out += ["", f"Wall time {f(r['wall_seconds'], 0)} s on {r['environment']['host']} (Python {r['environment']['python']}, NumPy {r['environment']['numpy']}, SciPy {r['environment']['scipy']}).", ""]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--analysis", type=Path, default=HERE / "results/analysis_e19.json")
    ap.add_argument("--out", type=Path, default=HERE / "results/results_tables_e19.md")
    args = ap.parse_args()
    r = json.loads(args.analysis.read_text())
    fc = {name: json.loads((HERE / f"forecasts/{name}.json").read_text())
          for name in ("e18_forecast", "e19_forecast_gold_target") if (HERE / f"forecasts/{name}.json").exists()}
    args.out.write_text(render(r, fc))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
